//! Build orchestration helpers: i18n generation, release packaging, self-test.

use crate::{repo_root, run_tool};
use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};

/// Location of upstream's string catalog. Only present in a developer checkout
/// that has cloned upstream; the generated Rust file is committed so a plain
/// build never needs it.
fn upstream_xcstrings() -> PathBuf {
    repo_root()
        .join("upstream")
        .join("Tinycast")
        .join("Resources")
        .join("Localizable.xcstrings")
}

/// The upstream interface languages, in the order upstream declares them.
pub const LANGUAGES: &[(&str, &str)] = &[
    ("en", "English"),
    ("ar", "Arabic"),
    ("de", "German"),
    ("es", "Spanish"),
    ("fr", "French"),
    ("ja", "Japanese"),
    ("ko", "Korean"),
    ("pt-BR", "Portuguese (Brazil)"),
    ("zh-Hans", "Chinese (Simplified)"),
];

/// Regenerate `crates/tc-i18n/src/strings.generated.rs` from upstream's
/// `Localizable.xcstrings`.
pub fn i18n() -> Result<()> {
    let source = upstream_xcstrings();
    if !source.exists() {
        bail!(
            "upstream string catalog not found at {}.\n\
             Clone upstream next to the repository (`git clone https://github.com/abue-ammar/tinycast upstream`) \
             before regenerating strings. The generated file is committed, so a normal build does not need this step.",
            source.display()
        );
    }
    let text = std::fs::read_to_string(&source).context("reading Localizable.xcstrings")?;
    let catalog: serde_json::Value = serde_json::from_str(&text).context("parsing Localizable.xcstrings")?;
    let strings = catalog
        .get("strings")
        .and_then(|s| s.as_object())
        .context("Localizable.xcstrings has no `strings` object")?;

    let mut entries: Vec<(String, Vec<(String, String)>)> = Vec::new();
    for (key, value) in strings {
        let mut translations: Vec<(String, String)> = Vec::new();
        if let Some(obj) = value.as_object() {
            if let Some(localizations) = obj.get("localizations").and_then(|l| l.as_object()) {
                for (lang, loc) in localizations {
                    if let Some(text) = loc.get("stringUnit").and_then(|s| s.get("value")).and_then(|v| v.as_str()) {
                        translations.push((lang.clone(), text.to_string()));
                    }
                }
            }
        }
        translations.sort_by(|a, b| a.0.cmp(&b.0));
        entries.push((key.clone(), translations));
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut out = String::new();
    out.push_str("// @generated by `cargo xtask i18n` from upstream/Tinycast/Resources/Localizable.xcstrings.\n");
    out.push_str("// Do not edit by hand.\n\n");
    out.push_str("/// Every localized interface language, as (BCP-47 tag, English name).\n");
    out.push_str("pub const LANGUAGES: &[(&str, &str)] = &[\n");
    for (code, name) in LANGUAGES {
        out.push_str(&format!("    ({:?}, {:?}),\n", code, name));
    }
    out.push_str("];\n\n");
    out.push_str("/// Every interface string upstream declares, with each translation.\n");
    out.push_str("///\n/// Entries are sorted by key. A language may be missing for a given key; the\n");
    out.push_str("/// English text is the fallback.\n");
    out.push_str("pub static STRINGS: &[(&str, &[(&str, &str)])] = &[\n");
    for (key, translations) in &entries {
        out.push_str(&format!("    ({:?}, &[", key));
        for (lang, text) in translations {
            out.push_str(&format!("({:?}, {:?}), ", lang, text));
        }
        out.push_str("]),\n");
    }
    out.push_str("];\n\n");
    out.push_str("/// Look up `key` in `lang`, falling back to English and then to the key itself.\n");
    out.push_str("pub fn lookup(key: &str, lang: &str) -> Option<&'static str> {\n");
    out.push_str("    let entry = STRINGS.iter().find(|(k, _)| *k == key)?;\n");
    out.push_str("    let hit = entry.1.iter().find(|(l, _)| *l == lang);\n");
    out.push_str("    let english = entry.1.iter().find(|(l, _)| *l == \"en\");\n");
    out.push_str("    hit.or(english).map(|(_, v)| *v)\n");
    out.push_str("}\n");

    let dest = repo_root().join("crates").join("tc-i18n").join("src").join("strings.generated.rs");
    std::fs::write(&dest, out).context("writing strings.generated.rs")?;
    println!("i18n: wrote {} ({} strings, {} languages)", dest.display(), entries.len(), LANGUAGES.len());
    Ok(())
}

/// One release artifact to produce.
struct Artifact {
    /// File name inside `dist/`.
    file: &'static str,
    /// Rust target triple.
    target: &'static str,
    /// NSIS architecture token.
    nsis_arch: &'static str,
}

const ARTIFACTS: &[Artifact] = &[
    Artifact { file: "x64", target: "x86_64-pc-windows-msvc", nsis_arch: "x64" },
    Artifact { file: "arm64", target: "aarch64-pc-windows-msvc", nsis_arch: "arm64" },
];

/// Build release binaries, the installer, the portable zip and the checksums.
pub fn dist(args: &[String]) -> Result<()> {
    let channel = flag_value(args, "--channel").unwrap_or_else(|| "stable".to_string());
    let only = flag_value(args, "--arch");
    let version = crate_version()?;
    let root = repo_root();
    let dist_dir = root.join("dist");
    std::fs::create_dir_all(&dist_dir).context("creating dist/")?;

    let binaries = ["yal", "yal-indexer", "yal-ocr", "yal-dictation"];
    let mut produced: Vec<PathBuf> = Vec::new();

    for artifact in ARTIFACTS {
        let file = artifact.file;
        let target = artifact.target;
        let nsis_arch = artifact.nsis_arch;
        if let Some(only) = &only {
            if only != file {
                continue;
            }
        }
        println!("dist: building {} ({})", target, file);
        run_tool(
            "cargo",
            &[
                "build",
                "--release",
                "--target",
                artifact.target,
                "--bin",
                "yal",
                "--bin",
                "yal-indexer",
                "--bin",
                "yal-ocr",
                "--bin",
                "yal-dictation",
            ],
            "release build",
        )?;

        let stage = dist_dir.join(format!("stage-{file}"));
        if stage.exists() {
            std::fs::remove_dir_all(&stage).ok();
        }
        std::fs::create_dir_all(&stage).context("creating staging directory")?;

        let profile_dir = root
            .join("target")
            .join(artifact.target)
            .join("release");
        for bin in binaries {
            let from = profile_dir.join(format!("{bin}.exe"));
            if !from.exists() {
                bail!("expected release binary {} was not produced", from.display());
            }
            std::fs::copy(&from, stage.join(format!("{bin}.exe")))
                .with_context(|| format!("staging {}", from.display()))?;
        }
        copy_if_present(&root.join("assets"), &stage)?;
        copy_if_present(&root.join("installer").join("assets"), &stage)?;
        // The portable build keeps its data beside the executable.
        std::fs::write(stage.join("portable"), b"yal portable marker\n")
            .context("writing portable marker")?;

        // Installer
        let nsi = root.join("installer").join("yal.nsi");
        if !nsi.exists() {
            bail!("installer script {} is missing", nsi.display());
        }
        let setup = dist_dir.join(format!("yal-setup-{version}-{file}.exe"));
        println!("dist: building installer {}", setup.display());
        let installer = std::path::Path::new(&nsi);
        let installer_display = installer.display().to_string();
        let setup_display = setup.display().to_string();
        run_tool(
            "makensis",
            &[
                "-V3",
                &format!("/DVERSION={version}"),
                &format!("/DARCH={file}"),
                &format!("/DNSIS_ARCH={nsis_arch}"),
                &format!("/DCHANNEL={channel}"),
                &format!("/DOUTFILE={setup_display}"),
                &installer_display,
            ],
            "NSIS installer build",
        )?;
        produced.push(setup);

        // Portable zip
        let zip_path = dist_dir.join(format!("yal-{version}-{file}-portable.zip"));
        println!("dist: building portable zip {}", zip_path.display());
        make_zip(&stage, &zip_path)?;
        produced.push(zip_path);
    }

    // Checksums
    let mut sums = String::new();
    for path in &produced {
        let digest = sha256_file(path)?;
        sums.push_str(&format!("{}  {}\n", digest, path.file_name().unwrap().to_string_lossy()));
    }
    let sums_path = dist_dir.join("SHA256SUMS.txt");
    std::fs::write(&sums_path, sums).context("writing SHA256SUMS.txt")?;
    println!("dist: wrote {}", sums_path.display());
    for path in &produced {
        println!("  {} ({})", path.display(), crate::human_bytes(std::fs::metadata(path)?.len()));
    }
    Ok(())
}

fn copy_if_present(dir: &Path, stage: &Path) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_file() {
            std::fs::copy(&path, stage.join(entry.file_name()))?;
        }
    }
    Ok(())
}

fn make_zip(stage: &Path, zip_path: &Path) -> Result<()> {
    use std::io::Write;
    let file = std::fs::File::create(zip_path).context("creating portable zip")?;
    let mut zip = zip::ZipWriter::new(file);
    let options = zip::write::FileOptions::<()>::default()
        .compression_method(zip::CompressionMethod::Deflated)
        .unix_permissions(0o755);
    let mut stack = vec![stage.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir)? {
            let entry = entry?;
            let path = entry.path();
            let name = path
                .strip_prefix(stage)
                .expect("staged path is under the staging directory")
                .to_string_lossy()
                .replace('\\', "/");
            if path.is_dir() {
                stack.push(path);
            } else {
                zip.start_file(name, options)?;
                let bytes = std::fs::read(&path)?;
                zip.write_all(&bytes)?;
            }
        }
    }
    zip.finish()?;
    Ok(())
}

/// Compute the SHA-256 of a file.
pub fn sha256_file(path: &Path) -> Result<String> {
    use sha2::{Digest, Sha256};
    let bytes = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
    let mut hasher = Sha256::new();
    hasher.update(&bytes);
    Ok(hex::encode(hasher.finalize()))
}

/// Read `--flag value` from an argument list.
fn flag_value(args: &[String], flag: &str) -> Option<String> {
    args.iter().position(|a| a == flag).and_then(|i| args.get(i + 1)).cloned()
}

/// The workspace version, taken from the root manifest.
pub fn crate_version() -> Result<String> {
    let manifest = repo_root().join("Cargo.toml");
    let text = std::fs::read_to_string(&manifest).context("reading Cargo.toml")?;
    for line in text.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("version = ") {
            if !line.starts_with(' ') {
                return Ok(rest.trim_matches('"').to_string());
            }
        }
    }
    bail!("could not find the workspace version in Cargo.toml")
}

/// Run the built launcher's self-test and print its JSON report.
pub fn selftest() -> Result<()> {
    let exe = repo_root().join("target").join("release").join("yal.exe");
    if !exe.exists() {
        bail!(
            "{} does not exist; run `cargo build --release --bin yal` first",
            exe.display()
        );
    }
    let output = std::process::Command::new(&exe)
        .arg("--self-test")
        .output()
        .with_context(|| format!("running {}", exe.display()))?;
    print!("{}", String::from_utf8_lossy(&output.stdout));
    eprint!("{}", String::from_utf8_lossy(&output.stderr));
    if !output.status.success() {
        bail!("self-test failed with status {}", output.status);
    }
    Ok(())
}
